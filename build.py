"""Build both executables.

    .venv\\Scripts\\python.exe build.py            # Chat Archiver + Chat Archiver Admin
    .venv\\Scripts\\python.exe build.py --app-only

Chat Archiver needs build/approval.json, exported from Chat Archiver Admin
(Settings → Export build config). That file holds only public data: the bot's
name and id and the owner's *verify* key. No API keys, no bot token, no private
key ever reach this script or the executables.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DIST = ROOT / "dist"
# flet pack deletes ./build and its dist folder on every run, so our files live elsewhere
WORK = ROOT / ".pack"
CONFIG = ROOT / "release" / "approval.json"
ASSETS = ROOT / "assets"
EMBEDDED = ROOT / "chat_archiver" / "_build_config.py"
VERSION = "1.0.0"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def make_icon(path: Path, bg: tuple, accent: tuple | None = None) -> None:
    """Our own simple archive-box icon (no Telegram branding)."""
    from PIL import Image, ImageDraw

    s = 256
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((8, 8, s - 8, s - 8), radius=56, fill=bg)
    white = (255, 255, 255, 255)
    d.rounded_rectangle((52, 66, 204, 104), radius=10, fill=white)               # lid
    d.rounded_rectangle((64, 110, 192, 196), radius=12, fill=white)              # box
    d.rounded_rectangle((104, 130, 152, 144), radius=7, fill=bg)                 # handle slot
    if accent:
        d.ellipse((168, 160, 236, 228), fill=accent, outline=white, width=8)     # admin badge
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


def admin_public_config() -> dict | None:
    """Public part of this PC's Chat Archiver Admin setup (bot + verify key), if configured."""
    import time
    from chat_archiver_admin.__main__ import data_path as vault_path
    from chat_archiver_admin.botapi import BotApi
    from chat_archiver_admin.service import AdminService
    from tg_export.vault import Vault
    svc = AdminService(vault=Vault(vault_path()), bot_factory=BotApi, clock=time.time)
    return svc.build_config() if svc.is_configured else None


def embed_config() -> dict:
    sys.path.insert(0, str(ROOT))
    exported = ROOT / "build" / "approval.json"          # where Admin's "Export build config" writes
    if exported.exists():
        CONFIG.parent.mkdir(exist_ok=True)
        shutil.copy2(exported, CONFIG)
    # the live Admin on this PC wins over an exported file, which may be stale after a key restore
    data = admin_public_config()
    if data is None and CONFIG.exists():
        data = json.loads(CONFIG.read_text("utf-8"))
    if data is None:
        sys.exit("Chat Archiver Admin is not set up on this PC. Open it, enter the bot token and API keys, "
                 "then run the build again (or put an exported approval.json into the release folder).")
    from chat_archiver.config import from_dict
    from_dict(data)                                  # validates the format
    public = {k: data[k] for k in ("bot_username", "bot_id", "owner_verify_key")}
    EMBEDDED.write_text("# Generated by build.py. Public data only.\nCONFIG = " + json.dumps(public) + "\n", "utf-8")
    return public


def pack(script: str, name: str, icon: Path, extra: list[str]) -> Path:
    # flet pack -y wipes its whole dist folder, so each exe gets its own and is copied out
    out = WORK / name
    flet = Path(sys.executable).with_name("flet.exe")
    cmd = [str(flet), "pack", script, "-n", name, "-i", str(icon), "-y", "--distpath", str(out),
           "--product-name", name, "--file-description", name, "--product-version", VERSION,
           "--file-version", VERSION + ".0", "--copyright", "Chat Archiver", *extra]
    print(">", " ".join(cmd))
    subprocess.run(cmd, cwd=ROOT, check=True)
    produced = out / f"{name}.exe"
    if not produced.exists():
        sys.exit(f"{produced} was not produced")
    DIST.mkdir(exist_ok=True)
    exe = DIST / produced.name
    shutil.copy2(produced, exe)
    return exe


def selftest(exe: Path) -> dict:
    out = WORK / f"selftest-{exe.stem.replace(' ', '_')}.json"
    out.unlink(missing_ok=True)
    code = subprocess.run([str(exe), "--selftest", str(out)], timeout=300).returncode
    result = json.loads(out.read_text("utf-8")) if out.exists() else {"ok": False, "error": "no output"}
    result["exit_code"] = code
    return result


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--app-only", action="store_true")
    ap.add_argument("--admin-only", action="store_true")
    args = ap.parse_args()
    WORK.mkdir(exist_ok=True)
    make_icon(ASSETS / "icon.ico", (79, 70, 229, 255))
    make_icon(ASSETS / "admin.ico", (30, 41, 59, 255), accent=(245, 158, 11, 255))

    built: list[Path] = []
    if not args.admin_only:
        public = embed_config()
        print(f"Embedding public config for @{public['bot_username']}")
        try:
            built.append(pack("chat_archiver_main.py", "Chat Archiver", ASSETS / "icon.ico",
                              ["--hidden-import", "chat_archiver._build_config"]))
        finally:
            EMBEDDED.unlink(missing_ok=True)         # dev runs keep reading build/approval.json
    if not args.app_only:
        built.append(pack("admin_main.py", "Chat Archiver Admin", ASSETS / "admin.ico",
                          ["--hidden-import", "chat_archiver_admin.__main__",
                           "--pyinstaller-build-args=--collect-submodules=chat_archiver_admin"]))

    ok = True
    for exe in built:
        res = selftest(exe)
        ok &= bool(res.get("ok")) and res["exit_code"] == 0
        size_mb = exe.stat().st_size / 1e6
        print(f"{exe.name}: {size_mb:.1f} MB, selftest {'OK' if res.get('ok') else 'FAILED'}")
        print(json.dumps(res, indent=2))
    lines = [f"{sha256(exe)}  {exe.name}" for exe in sorted(DIST.glob("*.exe"))]
    (DIST / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", "utf-8")
    print((DIST / "SHA256SUMS.txt").read_text("utf-8"))
    shutil.rmtree(ROOT / "build", ignore_errors=True)    # PyInstaller work files
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
